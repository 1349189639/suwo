function waterOf(f: FoodItem): number | undefined {
  const byCat = WATER_BY_CATEGORY[f.category]
  if (byCat) return byCat
  const hit = WATER_BY_NAME.find(([k]) => f.name.includes(k))
  return hit ? hit[1] : undefined
}

export const FOODS: FoodItem[] = SPECS.map((spec, i) => ({
  ...spec,
  per100: { ...spec.per100, fiber: spec.per100.fiber ?? FIBER_BY_CATEGORY[spec.category] },
  id: `f${String(i + 1).padStart(3, '0')}`,
})).map((f) => {
  const w = waterOf(f)
  return w === undefined ? f : { ...f, per100: { ...f.per100, water: w } }
})

export const ALL_FOODS = FOODS

export function searchFoods(query: string, custom: FoodItem[], limit = 60): FoodItem[] {
  const q = query.trim().toLowerCase()
  const pool = [...FOODS, ...custom]
  if (!q) return pool
  return pool
    .filter(
      (f) =>
        f.name.toLowerCase().includes(q) ||
        f.tags.some((t) => t.toLowerCase().includes(q)),
    )
    .slice(0, limit)
}

export function filterFoods(
  query: string,
  custom: FoodItem[],
  category: FoodCategory | 'all' | 'custom',
): FoodItem[] {
  const q = query.trim().toLowerCase()
  const all = [...FOODS, ...custom]
  // 有关键词时忽略分类：搜「玉米」不该被当前分类挡住
  const scoped = q
    ? category === 'custom'
      ? custom
      : all
    : category === 'custom'
      ? custom
      : category === 'all'
        ? all
        : all.filter((f) => f.category === category)
  if (!q) return scoped
  return scoped.filter(
    (f) =>
      f.name.toLowerCase().includes(q) ||
      f.tags.some((t) => t.toLowerCase().includes(q)),
  )
}

export function countByCategory(category: FoodCategory): number {
  return FOODS.filter((f) => f.category === category).length
}

